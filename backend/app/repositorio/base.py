"""Contrato de acesso a dados.

As rotas falam com esta interface, não com o Supabase. Há duas implementações:

* `RepositorioSupabase` — produção. Um cliente por requisição, autenticado com
  o JWT do usuário, para a RLS valer no banco **e** no Storage.
* `RepositorioMemoria` — modo demonstração e testes. Mesmas regras, sem rede.

Ter as duas atrás do mesmo contrato é o que permite testar as rotas inteiras
(incluindo os cenários de bug) em milissegundos, e apresentar o projeto num
auditório sem depender do Wi-Fi.
"""

from __future__ import annotations

from typing import Protocol


class Repositorio(Protocol):
    # ------------------------------------------------------------- peças
    def listar_pecas(self, *, papel: str | None = None, categoria: str | None = None,
                     cor: str | None = None, disponivel: bool | None = None) -> list[dict]: ...
    def obter_peca(self, peca_id: str) -> dict | None: ...
    def criar_peca(self, dados: dict) -> dict: ...
    def atualizar_peca(self, peca_id: str, campos: dict) -> dict | None: ...
    def remover_peca(self, peca_id: str) -> dict | None: ...
    def remover_fotos(self, caminhos: list[str]) -> list[str]: ...
    def foto_existe(self, caminho: str) -> bool: ...

    # ------------------------------------------------------ recomendação
    def usos_recentes(self, janela: int) -> dict[str, int]: ...
    def aprovacao_por_categoria(self, limite: int) -> dict[str, tuple[int, int]]: ...
    def pesos(self) -> dict | None: ...
    def salvar_pesos(self, pesos: dict) -> None: ...
    def registrar_recomendacao(self, contexto: dict, looks: list[dict]) -> None: ...
    def obter_look(self, look_id: str) -> dict | None: ...
    def registrar_feedback(self, look_id: str, aprovado: bool) -> None: ...
    def marcar_look_salvo(self, look_id: str, salvo: bool) -> bool: ...
    def listar_looks(self, *, salvos: bool, limite: int) -> list[dict]: ...
    def metricas(self) -> dict: ...

    # ----------------------------------------------------- perfil e LGPD
    def perfil(self) -> dict: ...
    def atualizar_perfil(self, nome: str) -> dict: ...
    def consentimento(self) -> dict | None: ...
    def registrar_consentimento(self, versao: str, finalidades: dict) -> dict: ...
    def revogar_consentimento(self) -> None: ...
    def exportar_dados(self) -> dict: ...
    def excluir_conta(self) -> dict: ...


METRICAS_VAZIAS = {
    "consultas": 0, "consultas_avaliadas": 0, "looks_mostrados": 0,
    "looks_aprovados": 0, "hit_rate_3": None, "precision_3": None,
}


def calcular_metricas(consultas: int, avaliadas: int, mostrados: int,
                      aprovados: int, com_acerto: int) -> dict:
    """Hit Rate@3 e Precision@3 (RNF04), com as definições usuais da literatura.

    * Hit Rate@3 = consultas com ao menos um look aprovado ÷ consultas avaliadas
    * Precision@3 = looks aprovados ÷ (3 × consultas avaliadas)

    "Avaliada" é a consulta que recebeu pelo menos um feedback. Uma consulta que
    o usuário abriu e fechou sem responder não diz se o motor acertou; contá-la
    como erro mediria engajamento, não qualidade. O total bruto vai em
    `consultas`, para quem quiser a variante estrita.
    """
    return {
        "consultas": consultas,
        "consultas_avaliadas": avaliadas,
        "looks_mostrados": mostrados,
        "looks_aprovados": aprovados,
        "hit_rate_3": round(com_acerto / avaliadas, 4) if avaliadas else None,
        "precision_3": round(aprovados / (3 * avaliadas), 4) if avaliadas else None,
    }
